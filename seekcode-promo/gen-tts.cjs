const edgeTts = require('edge-tts');
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const OUT = 'c:/Users/???/Desktop/SeekCode/seekcode-promo';
const scenes = [
  ['tts-scene1.mp3', '??????AI???????????????????'],
  ['tts-scene2.mp3', '?????????????AI?????'],
  ['tts-scene3.mp3', '???????AI????????????????'],
  ['tts-scene4.mp3', '?????????????????????????'],
  ['tts-scene5.mp3', '?????????????Flash????????Pro?????'],
  ['tts-scene6.mp3', '?????????????GitHub??Star??????????'],
];

(async () => {
  for (const [id, text] of scenes) {
    console.log('Gen:', text);
    const Comm = edgeTts.EdgeTts;
    const c = new Comm(text, 'zh-CN-YunxiNeural');
    const stream = await c.run();
    const chunks = [];
    for await (const chunk of stream) { chunks.push(chunk); }
    fs.writeFileSync(id, Buffer.concat(chunks));
    const probe = execSync('"' + path.join(OUT, 'ffprobe.exe') + '" -v quiet -print_format json -show_format "' + id + '"', { encoding: 'utf8' });
    const dur = JSON.parse(probe).format.duration;
    console.log('  -> ' + dur.toFixed(2) + 's -> ' + id);
  }
  console.log('ALL DONE');
})();
